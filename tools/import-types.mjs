import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const vendor = new URL('./vendor/pokeapi/', import.meta.url);
const rows = (file) => readFileSync(new URL(file, vendor), 'utf8').trim().split(/\r?\n/).slice(1).map(row => row.split(','));
const types = rows('types.csv').filter(([id]) => Number(id) >= 1 && Number(id) <= 18).map(([, name]) => name);
const entries = rows('type_efficacy.csv');
const chart = types.map((_, attack) => types.map((_, defense) => {
  const row = entries.find(([a, d]) => Number(a) === attack + 1 && Number(d) === defense + 1);
  if (!row || ![0, 50, 100, 200].includes(Number(row[2]))) throw new Error('Tabla incompleta o no válida.');
  return Number(row[2]) / 100;
}));
const generated = `// Generated by tools/import-types.mjs from the pinned PokeAPI CSVs. Do not edit.\nexport const POKEMON_TYPES = ${JSON.stringify(types)} as const;\nexport type PokemonType = typeof POKEMON_TYPES[number];\nexport const TYPE_CHART: readonly (readonly number[])[] = [\n${chart.map(row => '  ' + JSON.stringify(row)).join(',\n')}\n];\n`;
writeFileSync(new URL('../src/data/type-chart.ts', import.meta.url), generated);
writeFileSync(new URL('sources.json', vendor), JSON.stringify({
  repository: 'https://github.com/PokeAPI/pokeapi',
  commit: '81d20919845b6a445969b9265aab5cec6b04cece',
  license: '../../../public/licenses/PokeAPI-BSD-3-Clause.txt',
  files: ['types.csv', 'type_efficacy.csv'].map(file => ({ file, sha256: createHash('sha256').update(readFileSync(new URL(file, vendor))).digest('hex') })),
  scope: '18 standard modern types; stellar, unknown and shadow excluded',
}, null, 2) + '\n');
console.log('18 tipos y 324 relaciones importadas desde CSV locales.');
